  SELECT FN_UNZONE(k.KOUZA_NO) KOUZA_NO, e.KANJI_UTF8 MEIGI_KANJI, e.KANA_UTF8 MEIGI_KANA,
       FN_EBC(k.SHUBETSU) SHUBETSU, FN_EBC(k.KAISETSU_BI) KAISETSU_BI, FN_EBC(k.JOUTAI) JOUTAI,
       FN_UNPACK(k.ZANDAKA) ZANDAKA, FN_EBC(e.BRANCH_CODE) BRANCH_CODE
FROM KOUZA k JOIN KOUZA_EXT e ON e.KOUZA_NO=k.KOUZA_NO
/

