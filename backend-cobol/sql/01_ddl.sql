CREATE OR REPLACE EDITIONABLE FUNCTION "FN_UNZONE" (r RAW) RETURN NUMBER IS
BEGIN
  IF r IS NULL THEN RETURN NULL; END IF;
  RETURN TO_NUMBER(REPLACE(RAWTOHEX(r),'F',''));
END;
/

CREATE OR REPLACE EDITIONABLE FUNCTION "FN_UNPACK" (r RAW) RETURN NUMBER IS
  h VARCHAR2(64);
BEGIN
  IF r IS NULL THEN RETURN NULL; END IF;
  h := RAWTOHEX(r);
  RETURN TO_NUMBER(SUBSTR(h,1,LENGTH(h)-1)) * CASE WHEN SUBSTR(h,-1)='D' THEN -1 ELSE 1 END;
END;
/

CREATE OR REPLACE EDITIONABLE FUNCTION "FN_EBC" (r RAW) RETURN VARCHAR2 IS
BEGIN
  IF r IS NULL THEN RETURN NULL; END IF;
  RETURN UTL_I18N.RAW_TO_CHAR(r, 'WE8EBCDIC500');
END;
/

CREATE OR REPLACE EDITIONABLE FUNCTION "KANA2EBC" (p IN NVARCHAR2) RETURN RAW IS
  v_ref NVARCHAR2(100) :=
    N'アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン';
  v_src NVARCHAR2(60);
  v_out RAW(20);
  v_ch  NVARCHAR2(1);
  v_idx PLS_INTEGER;
  v_b   PLS_INTEGER;
BEGIN
  -- 濁音・半濁音は清音へ寄せる(デモ用)
  v_src := TRANSLATE(p,
    N'ガギグゲゴザジズゼゾダヂヅデドバビブベボパピプペポ',
    N'カキクケコサシスセソタチツテトハヒフヘホハヒフヘホ');
  v_out := UTL_RAW.CAST_TO_RAW('');
  FOR i IN 1 .. LEAST(NVL(LENGTH(v_src),0), 20) LOOP
    v_ch  := SUBSTR(v_src, i, 1);
    v_idx := INSTR(v_ref, v_ch);
    IF v_idx = 0 THEN v_b := 64; ELSE v_b := 65 + v_idx; END IF;  -- 0x41+idx
    v_out := UTL_RAW.CONCAT(v_out, UTL_RAW.SUBSTR(UTL_RAW.CAST_TO_RAW(CHR(v_b)), 1, 1));
  END LOOP;
  -- 20byte まで EBCDIC 空白(0x40)でパディング
  WHILE UTL_RAW.LENGTH(v_out) < 20 LOOP
    v_out := UTL_RAW.CONCAT(v_out, HEXTORAW('40'));
  END LOOP;
  RETURN UTL_RAW.SUBSTR(v_out, 1, 20);
END;
/

CREATE OR REPLACE EDITIONABLE FUNCTION "KANJI2EBC" (p IN NVARCHAR2) RETURN RAW IS
  v_out RAW(30);
  v_n   PLS_INTEGER;
  v_hi  PLS_INTEGER;
  v_lo  PLS_INTEGER;
BEGIN
  -- SO(0x0E) で DBCS 開始
  v_out := HEXTORAW('0E');
  v_n := NVL(LENGTH(p), 0);
  FOR i IN 1 .. v_n LOOP
    -- プレースホルダ DBCS 2byte(実バイトはエンコーダ確定後に差替)
    v_hi := 66 + MOD(i, 20);          -- 0x42..
    v_lo := 66 + MOD(i * 3, 20);
    v_out := UTL_RAW.CONCAT(v_out,
               UTL_RAW.CONCAT(UTL_RAW.SUBSTR(UTL_RAW.CAST_TO_RAW(CHR(v_hi)),1,1),
                              UTL_RAW.SUBSTR(UTL_RAW.CAST_TO_RAW(CHR(v_lo)),1,1)));
  END LOOP;
  -- SI(0x0F) で SBCS へ戻す
  v_out := UTL_RAW.CONCAT(v_out, HEXTORAW('0F'));
  -- 空白(0x40)パディング
  WHILE UTL_RAW.LENGTH(v_out) < 20 LOOP
    v_out := UTL_RAW.CONCAT(v_out, HEXTORAW('40'));
  END LOOP;
  -- ★結定打3★ X(20) の 20byte 境界で切り詰め(SO/SI 含む)
  RETURN UTL_RAW.SUBSTR(v_out, 1, 20);
END;
/

